DROP DATABASE IF EXISTS pluviometria_temperatura;
CREATE DATABASE pluviometria_temperatura CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE pluviometria_temperatura;

CREATE TABLE pltemp_continentes (
    id_continente INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE pltemp_paises (
    id_pais INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    id_continente INT NOT NULL,
    FOREIGN KEY (id_continente) REFERENCES pltemp_continentes(id_continente)
);

CREATE TABLE pltemp_zonas (
    id_zona INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    id_pais INT NOT NULL,
    UNIQUE (id_pais, nombre),
    FOREIGN KEY (id_pais) REFERENCES pltemp_paises(id_pais)
);

CREATE TABLE pltemp_pluviometria (
    id INT AUTO_INCREMENT PRIMARY KEY,
    id_zona INT NOT NULL,
    pl_precipitacion_actual INT NOT NULL,
    pl_precipitacion_anterior INT,
    pl_unidad VARCHAR(10) NOT NULL DEFAULT 'mm',
    fecha_referencia DATE NOT NULL,
    temp_valor INT NOT NULL,
    temp_unidad VARCHAR(10) NOT NULL DEFAULT 'ºC',
    FOREIGN KEY (id_zona) REFERENCES pltemp_zonas(id_zona)
);

